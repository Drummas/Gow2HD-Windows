#!/usr/bin/env python3
"""Writes the launcher's version resource from LAUNCHER_VERSION in src/config.h.

The version is not written by hand into the resource: FILEVERSION/PRODUCTVERSION, the FileVersion/ProductVersion
strings and the manifest's assembly version are all generated from the one LAUNCHER_VERSION constant, so the exe
cannot report a version other than the one it was built as (and bumping the version stays a single edit).

    python tools/version_header.py src/config.h res/app.manifest build

writes

    build/launcher_version.h   included by res/app.rc
    build/launcher.manifest    res/app.manifest with the version filled in, embedded as resource 1 24

Run by build.cmd before windres.
"""

import os
import re
import sys

# LAUNCHER_VERSION "0.1.1" (LAUNCHER_VERSION_W does not match: the name has to be followed by whitespace)
VERSION_RE = re.compile(r'^[ \t]*#[ \t]*define[ \t]+LAUNCHER_VERSION[ \t]+"([^"]*)"[ \t]*(?://.*)?$', re.MULTILINE)
PARTS_RE = re.compile(r'^(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?$')
# The application manifest's own assembly version (the Common-Controls dependency below it is left alone).
MANIFEST_RE = re.compile(r'(<assemblyIdentity\b[^>]*\bversion=")[^"]*(")')

HEADER = """\
// Generated by tools/version_header.py from LAUNCHER_VERSION in src/config.h. Do not edit.
#define LAUNCHER_VERSION_STR      "{version}"
#define LAUNCHER_VERSION_COMMA    {comma}
#define LAUNCHER_VERSION_DOTTED4  {dotted4}
"""


def read_version(config_path):
    """LAUNCHER_VERSION as written in config.h, e.g. "0.1.1"."""
    with open(config_path, encoding="utf-8") as f:
        text = f.read()
    found = VERSION_RE.findall(text)
    if len(found) != 1:
        raise SystemExit(f"error: expected exactly one LAUNCHER_VERSION in {config_path}, found {len(found)}")
    return found[0]


def version_parts(version):
    """(0, 1, 1) for "0.1.1"; a fourth number is kept when the version has one."""
    m = PARTS_RE.match(version)
    if not m:
        raise SystemExit(f'error: LAUNCHER_VERSION "{version}" is not X.Y.Z or X.Y.Z.W; '
                         "the resource's FILEVERSION needs numbers, so a suffix like -rc1 cannot be used")
    parts = [int(p) for p in m.groups() if p is not None]
    if len(parts) == 3:
        parts.append(0)
    for p in parts:
        if p > 65535:
            raise SystemExit(f'error: LAUNCHER_VERSION "{version}" has a part above 65535')
    return parts


def main(argv):
    if len(argv) != 4:
        print("usage: version_header.py <config.h> <app.manifest> <out dir>", file=sys.stderr)
        return 2
    config_path, manifest_path, out_dir = argv[1], argv[2], argv[3]

    version = read_version(config_path)
    parts = version_parts(version)
    comma = ",".join(str(p) for p in parts)
    dotted4 = ".".join(str(p) for p in parts)

    os.makedirs(out_dir, exist_ok=True)
    header_path = os.path.join(out_dir, "launcher_version.h")
    with open(header_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(version=version, comma=comma, dotted4=dotted4))

    with open(manifest_path, encoding="utf-8") as f:
        manifest = f.read()
    manifest, count = MANIFEST_RE.subn(lambda m: m.group(1) + dotted4 + m.group(2), manifest, count=1)
    if count != 1:
        raise SystemExit(f"error: {manifest_path} has no <assemblyIdentity ... version=\"...\"> to fill in")
    manifest_out = os.path.join(out_dir, "launcher.manifest")
    with open(manifest_out, "w", encoding="utf-8", newline="\n") as f:
        f.write(manifest)

    print(f"version {version}: FILEVERSION/PRODUCTVERSION {comma}, assembly {dotted4}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
